USE COMPUNIC_V5;

-- 1. Usar stored procedure para agregar columnas solo si no existen
DROP PROCEDURE IF EXISTS sp_migrar_pagos;

DELIMITER $$
CREATE PROCEDURE sp_migrar_pagos()
BEGIN
    -- Columna ESTADO_PAGO en VENTAS
    IF NOT EXISTS (
        SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'VENTAS' AND COLUMN_NAME = 'ESTADO_PAGO'
    ) THEN
        ALTER TABLE VENTAS ADD COLUMN ESTADO_PAGO ENUM('PENDIENTE','VERIFICANDO','CONFIRMADO','RECHAZADO') NOT NULL DEFAULT 'CONFIRMADO';
    END IF;

    -- Columna METODO_PAGO en VENTAS
    IF NOT EXISTS (
        SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'VENTAS' AND COLUMN_NAME = 'METODO_PAGO'
    ) THEN
        ALTER TABLE VENTAS ADD COLUMN METODO_PAGO VARCHAR(100) NULL;
    END IF;

    -- Columna ORIGEN en VENTAS
    IF NOT EXISTS (
        SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'VENTAS' AND COLUMN_NAME = 'ORIGEN'
    ) THEN
        ALTER TABLE VENTAS ADD COLUMN ORIGEN ENUM('TIENDA_WEB','MOSTRADOR') NOT NULL DEFAULT 'MOSTRADOR';
    END IF;

    -- Columna NOTAS_PAGO en VENTAS
    IF NOT EXISTS (
        SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'VENTAS' AND COLUMN_NAME = 'NOTAS_PAGO'
    ) THEN
        ALTER TABLE VENTAS ADD COLUMN NOTAS_PAGO VARCHAR(500) NULL;
    END IF;

    -- Columna PUNTOS en CLIENTES
    IF NOT EXISTS (
        SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'CLIENTES' AND COLUMN_NAME = 'PUNTOS'
    ) THEN
        ALTER TABLE CLIENTES ADD COLUMN PUNTOS INT NOT NULL DEFAULT 0;
    END IF;
END$$
DELIMITER ;

CALL sp_migrar_pagos();
DROP PROCEDURE IF EXISTS sp_migrar_pagos;

-- 2. Crear tabla COMPROBANTES_PAGO
CREATE TABLE IF NOT EXISTS COMPROBANTES_PAGO (
    ID_COMPROBANTE INT PRIMARY KEY AUTO_INCREMENT,
    ID_VENTA       INT NOT NULL,
    RUTA_IMAGEN    VARCHAR(500) NOT NULL,
    NOMBRE_ARCHIVO VARCHAR(255) NOT NULL,
    FECHA_SUBIDA   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    NOTAS_CLIENTE  VARCHAR(500) NULL,
    FOREIGN KEY (ID_VENTA) REFERENCES VENTAS(ID_VENTA) ON DELETE CASCADE,
    INDEX idx_id_venta (ID_VENTA)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 3. Marcar ventas del mostrador existentes como CONFIRMADO
UPDATE VENTAS SET ESTADO_PAGO = 'CONFIRMADO', ORIGEN = 'MOSTRADOR'
WHERE FACTURA NOT LIKE 'WEB-%';

-- 4. Marcar ventas web existentes
UPDATE VENTAS SET ORIGEN = 'TIENDA_WEB'
WHERE FACTURA LIKE 'WEB-%';

SELECT 'Migracion completada exitosamente' AS resultado;
